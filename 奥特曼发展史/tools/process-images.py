import os, io, json, base64
from PIL import Image, ImageDraw, ImageFilter
import numpy as np

SRC = os.path.join(os.getcwd(), "assets", "heroes")
OUT = os.path.join(os.getcwd(), "assets", "processed")
os.makedirs(OUT, exist_ok=True)

def cut_white(im):
    """Remove connected near-white background from the border."""
    im = im.convert("RGBA")
    rgb = im.convert("RGB")
    # flood from all four corners on a working copy
    work = rgb.copy()
    w, h = work.size
    for pt in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        if work.getpixel(pt)[0] > 235 and work.getpixel(pt)[1] > 235 and work.getpixel(pt)[2] > 235:
            ImageDraw.floodfill(work, pt, (255, 0, 255), thresh=24)
    arr = np.array(work)
    bg = (arr[:, :, 0] > 250) & (arr[:, :, 1] < 8) & (arr[:, :, 2] > 250)
    # soften the cut edge a little
    alpha = np.where(bg, 0, 255).astype(np.uint8)
    alpha_img = Image.fromarray(alpha, "L").filter(ImageFilter.GaussianBlur(0.6))
    out = im.copy()
    out.putalpha(alpha_img)
    return out

def process(name):
    im = Image.open(os.path.join(SRC, name))
    im = im.convert("RGBA")
    # remove white background for JPEG sources
    if name.lower().endswith((".jpg", ".jpeg")):
        im = cut_white(im)
    # crop transparent margins
    bbox = im.getchannel("A").getbbox()
    if bbox:
        im = im.crop(bbox)
    # resize to height 720 max
    h = 720
    w = round(im.width * (h / im.height))
    im = im.resize((w, h), Image.LANCZOS)
    out = os.path.join(OUT, os.path.splitext(name)[0] + ".webp")
    im.save(out, "WEBP", quality=84, method=6)
    return out, os.path.getsize(out)

files = [f for f in os.listdir(SRC) if f.lower().endswith((".png", ".jpg", ".jpeg", ".webp"))]
data = {}
total = 0
for f in sorted(files):
    out, size = process(f)
    key = os.path.splitext(f)[0]
    with open(out, "rb") as fh:
        data[key] = "data:image/webp;base64," + base64.b64encode(fh.read()).decode("ascii")
    total += size
    print(f"{key:12s} {size/1024:6.1f} KB  {Image.open(out).size}")

js = "/* ============================================================\n   IMAGES — official character visuals, locally embedded\n   © TSUBURAYA PRODUCTIONS. Non-commercial fan archive use.\n   Generated by tools/process-images.py\n   ============================================================ */\n"
js += "window.HERO_IMG = {\n"
for k, v in data.items():
    js += f'  {json.dumps(k)}: "{v}",\n'
js = js.rstrip(",\n") + "\n};\n"
with open(os.path.join(os.getcwd(), "src", "js", "images.js"), "w", encoding="utf-8") as fh:
    fh.write(js)
print("TOTAL", round(total/1024), "KB; data-uri JS", round(os.path.getsize("src/js/images.js")/1024), "KB")
